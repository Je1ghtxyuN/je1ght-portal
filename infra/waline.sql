CREATE TABLE IF NOT EXISTS wl_Users (
  objectId INT UNSIGNED NOT NULL AUTO_INCREMENT,
  display_name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  password VARCHAR(255) NOT NULL,
  type VARCHAR(30) DEFAULT NULL,
  label VARCHAR(255) DEFAULT NULL,
  url VARCHAR(255) DEFAULT NULL,
  avatar VARCHAR(255) DEFAULT NULL,
  github VARCHAR(255) DEFAULT NULL,
  twitter VARCHAR(255) DEFAULT NULL,
  facebook VARCHAR(255) DEFAULT NULL,
  google VARCHAR(255) DEFAULT NULL,
  weibo VARCHAR(255) DEFAULT NULL,
  qq VARCHAR(255) DEFAULT NULL,
  `2fa` VARCHAR(255) DEFAULT NULL,
  createdAt DATETIME DEFAULT NULL,
  updatedAt DATETIME DEFAULT NULL,
  PRIMARY KEY (objectId),
  UNIQUE KEY email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS wl_Comment (
  objectId INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED DEFAULT NULL,
  comment TEXT,
  insertedAt DATETIME DEFAULT NULL,
  createdAt DATETIME DEFAULT NULL,
  updatedAt DATETIME DEFAULT NULL,
  ip VARCHAR(45) DEFAULT NULL,
  likes INT UNSIGNED DEFAULT '0',
  ua TEXT,
  master TINYINT(1) DEFAULT '0',
  approved TINYINT(1) DEFAULT '1',
  sticky TINYINT(1) DEFAULT '0',
  spam TINYINT(1) DEFAULT '0',
  status VARCHAR(20) DEFAULT NULL,
  url VARCHAR(255) DEFAULT NULL,
  pid INT UNSIGNED DEFAULT NULL,
  rid INT UNSIGNED DEFAULT NULL,
  level INT UNSIGNED DEFAULT '0',
  PRIMARY KEY (objectId),
  KEY user_id (user_id),
  KEY url (url),
  KEY pid (pid),
  KEY rid (rid),
  CONSTRAINT wl_Comment_ibfk_1 FOREIGN KEY (user_id) REFERENCES wl_Users (objectId) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS wl_Counter (
  objectId INT UNSIGNED NOT NULL AUTO_INCREMENT,
  url VARCHAR(255) NOT NULL,
  time INT UNSIGNED DEFAULT NULL,
  reaction0 INT UNSIGNED DEFAULT '0',
  reaction1 INT UNSIGNED DEFAULT '0',
  reaction2 INT UNSIGNED DEFAULT '0',
  reaction3 INT UNSIGNED DEFAULT '0',
  reaction4 INT UNSIGNED DEFAULT '0',
  reaction5 INT UNSIGNED DEFAULT '0',
  reaction6 INT UNSIGNED DEFAULT '0',
  reaction7 INT UNSIGNED DEFAULT '0',
  reaction8 INT UNSIGNED DEFAULT '0',
  PRIMARY KEY (objectId),
  UNIQUE KEY url (url)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
